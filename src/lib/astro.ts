import {
  lifePath,
  personalYear,
  sunSign,
  ZODIAC_SIGNS,
} from './calc'
import type { BirthDate } from './calc'

export function parseBirthDate(raw: string): BirthDate | null {
  const m = /^(\d{1,2})\.(\d{1,2})\.(\d{4})$/.exec(raw.trim())
  if (!m) return null
  const day = Number(m[1])
  const month = Number(m[2])
  const year = Number(m[3])
  if (month < 1 || month > 12 || year < 1900 || year > 2100) return null
  return { day, month, year }
}

export function numerologySummary(date: BirthDate, year: number) {
  const lp = lifePath(date)
  const py = personalYear(date, year)
  return {
    lifePath: lp,
    personalYear: py,
    isMaster: lp === 11 || lp === 22 || lp === 33,
  }
}

export function zodiacSummary(date: BirthDate) {
  const sign = sunSign(date.day, date.month)
  return { index: sign.index, name: ZODIAC_SIGNS[sign.index] }
}

